#!/usr/bin/env python3
"""
Parse an Apple/GPTK Metal HUD HTML benchmark report.

Usage:
    python3 metal_hud_parser.py report.html
    python3 metal_hud_parser.py report.html --json
    python3 metal_hud_parser.py report.html --csv output.csv

The parser intentionally computes benchmark FPS from the raw frame-interval
series rather than using the HUD "FPS Average" field, because the raw frame
interval distribution provides the underlying timing data.

1% / 0.1% low definition used here:
    - Ignore zero frame intervals (the report labels these as missed frames).
    - Convert each positive frame interval to instantaneous FPS.
    - Sort FPS ascending.
    - 1% low = mean FPS of the slowest 1% positive intervals.
    - 0.1% low = mean FPS of the slowest 0.1% positive intervals.

Keep this methodology identical across all benchmark runs.
"""

import argparse
import csv
import json
import math
import re
import statistics
import sys
from pathlib import Path


def extract_json_script(text, script_id):
    pattern = (
        r'<script[^>]*id=["\']'
        + re.escape(script_id)
        + r'["\'][^>]*>(.*?)</script>'
    )
    m = re.search(pattern, text, re.IGNORECASE | re.DOTALL)
    if not m:
        raise ValueError(f"Could not find script id={script_id!r}")
    return json.loads(m.group(1).strip())


def strip_tags(s):
    return re.sub(r"<[^>]+>", " ", s)


def norm(s):
    return re.sub(r"\s+", " ", strip_tags(s)).strip()


def extract_report_text(text):
    # HTML is generated by the Metal HUD report. We only need visible text
    # for metadata/metrics that are not already in the raw frame series.
    text = re.sub(r"<script\b.*?</script>", " ", text, flags=re.I | re.S)
    text = re.sub(r"<style\b.*?</style>", " ", text, flags=re.I | re.S)
    return norm(text)


def first_match(patterns, text, cast=str):
    for pattern in patterns:
        m = re.search(pattern, text, re.I | re.S)
        if m:
            value = m.group(1).strip()
            try:
                return cast(value)
            except (ValueError, TypeError):
                pass
    return None


def percentile(values, p):
    """Linear percentile, matching common statistical percentile behavior."""
    if not values:
        return None
    if len(values) == 1:
        return values[0]
    x = (len(values) - 1) * p
    lo = math.floor(x)
    hi = math.ceil(x)
    if lo == hi:
        return values[lo]
    return values[lo] + (values[hi] - values[lo]) * (x - lo)


def low_fps(values, fraction):
    """
    Mean FPS of the slowest fraction of positive frame intervals.
    """
    fps = sorted(1000.0 / ms for ms in values if ms > 0)
    if not fps:
        return None
    n = max(1, math.ceil(len(fps) * fraction))
    return statistics.fmean(fps[:n])


def parse_report(path):
    text = Path(path).read_text(encoding="utf-8", errors="replace")
    visible = extract_report_text(text)

    raw = extract_json_script(text, "frameintervaldata")
    intervals_ns = raw.get("frameintervals")
    if not isinstance(intervals_ns, list):
        raise ValueError("frameintervaldata does not contain a 'frameintervals' list")

    intervals_ms = [float(x) / 1_000_000.0 for x in intervals_ns]

    total_entries = len(intervals_ms)
    missed_frames = sum(1 for x in intervals_ms if x == 0)
    positive = [x for x in intervals_ms if x > 0]

    if not positive:
        raise ValueError("No positive frame intervals found")

    # This matches the report's frame-interval average, which includes zeros.
    total_interval_ms = sum(intervals_ms)
    duration_s = total_interval_ms / 1000.0
    average_fps_from_intervals = total_entries / duration_s if duration_s else None
    average_frame_time_ms = statistics.fmean(intervals_ms)

    positive_mean_frame_time_ms = statistics.fmean(positive)

    # Low-FPS metrics: explicitly defined above.
    one_percent_low = low_fps(positive, 0.01)
    point_one_percent_low = low_fps(positive, 0.001)

    # Frame-time tail metrics.
    sorted_positive_ms = sorted(positive)
    p95_frame_time_ms = percentile(sorted_positive_ms, 0.95)
    p99_frame_time_ms = percentile(sorted_positive_ms, 0.99)
    p99_9_frame_time_ms = percentile(sorted_positive_ms, 0.999)

    result = {
        "file": str(path),
        "benchmark": {
            "duration_seconds": duration_s,
            "duration_formatted": f"{int(duration_s // 60)}:{duration_s % 60:04.1f}",
            "total_frame_intervals": total_entries,
            "positive_frame_intervals": len(positive),
            "missed_frames": missed_frames,
        },
        "fps": {
            "average_from_frame_intervals": average_fps_from_intervals,
            "one_percent_low": one_percent_low,
            "zero_point_one_percent_low": point_one_percent_low,
        },
        "frame_time_ms": {
            "average": average_frame_time_ms,
            "average_positive_only": positive_mean_frame_time_ms,
            "min": min(positive),
            "max": max(intervals_ms),
            "p95": p95_frame_time_ms,
            "p99": p99_frame_time_ms,
            "p99_9": p99_9_frame_time_ms,
            "standard_deviation": statistics.pstdev(intervals_ms),
        },
        "raw_report_metrics": {},
    }

    # Extract useful report metadata/metrics when present.
    metadata_patterns = {
        "resolution": [
            r"Resolution\s*</?[^>]*>\s*([0-9]+\s*x\s*[0-9]+)",
            r"Resolution\s+([0-9]+\s*x\s*[0-9]+)",
        ],
        "graphics_api": [
            r"Graphics API\s*</?[^>]*>\s*([^<]+)",
            r"Graphics API\s+([A-Za-z0-9._/-]+)",
        ],
        "gptk_version": [
            r"GPTK Version\s*</?[^>]*>\s*([^<]+)",
            r"GPTK Version\s+([A-Za-z0-9._-]+)",
        ],
        "content_scale": [
            r"Content Scale\s*</?[^>]*>\s*([0-9.]+)",
            r"Content Scale\s+([0-9.]+)",
        ],
        "pixel_format": [
            r"Pixel Format\s*</?[^>]*>\s*([^<]+)",
            r"Pixel Format\s+([A-Za-z0-9]+)",
        ],
        "fps_average_reported": [
            r"FPS Average\s*</?[^>]*>\s*([0-9.]+)",
            r"FPS Average\s+([0-9.]+)",
        ],
        "fps_last_reported": [
            r"FPS Last\s*</?[^>]*>\s*([0-9.]+)",
            r"FPS Last\s+([0-9.]+)",
        ],
        "fps_min_reported": [
            r"FPS Min\s*</?[^>]*>\s*([0-9.]+)",
            r"FPS Min\s+([0-9.]+)",
        ],
        "fps_max_reported": [
            r"FPS Max\s*</?[^>]*>\s*([0-9.]+)",
            r"FPS Max\s+([0-9.]+)",
        ],
        "frame_interval_average_reported_ms": [
            r"Frame Interval Average\s*</?[^>]*>\s*([0-9.]+)\s*ms",
            r"Frame Interval Average\s+([0-9.]+)\s*ms",
        ],
        "frame_interval_max_reported_ms": [
            r"Frame Interval Max\s*</?[^>]*>\s*([0-9.]+)\s*ms",
            r"Frame Interval Max\s+([0-9.]+)\s*ms",
        ],
    }

    for key, patterns in metadata_patterns.items():
        value = first_match(patterns, text)
        if value is None:
            # Try the visible-text version as a fallback.
            value = first_match(patterns, visible)
        if value is not None:
            result["raw_report_metrics"][key] = value

    # Prefer numeric values for known numeric fields.
    for key in list(result["raw_report_metrics"]):
        if key not in {"resolution", "graphics_api", "gptk_version", "pixel_format"}:
            try:
                result["raw_report_metrics"][key] = float(result["raw_report_metrics"][key])
            except ValueError:
                pass

    # Useful consistency checks.
    result["checks"] = {
        "reported_missed_frames_matches_raw": (
            result["raw_report_metrics"].get("missed_frames_reported") == missed_frames
            if "missed_frames_reported" in result["raw_report_metrics"]
            else None
        ),
        "average_frame_time_matches_raw": (
            abs(
                result["raw_report_metrics"].get("frame_interval_average_reported_ms", average_frame_time_ms)
                - average_frame_time_ms
            ) < 0.05
            if "frame_interval_average_reported_ms" in result["raw_report_metrics"]
            else None
        ),
    }

    return result


def print_human(result):
    b = result["benchmark"]
    f = result["fps"]
    ft = result["frame_time_ms"]
    raw = result["raw_report_metrics"]

    print("\n=== Metal HUD Benchmark ===")
    print(f"File:              {result['file']}")
    print(f"Duration:           {b['duration_formatted']}")
    print(f"Frame intervals:    {b['total_frame_intervals']:,}")
    print(f"Missed frames:      {b['missed_frames']:,}")
    print()
    print(f"Average FPS:        {f['average_from_frame_intervals']:.2f}")
    print(f"1% Low:             {f['one_percent_low']:.2f}")
    print(f"0.1% Low:           {f['zero_point_one_percent_low']:.2f}")
    print()
    print(f"Avg frame time:     {ft['average']:.2f} ms")
    print(f"P95 frame time:     {ft['p95']:.2f} ms")
    print(f"P99 frame time:     {ft['p99']:.2f} ms")
    print(f"P99.9 frame time:   {ft['p99_9']:.2f} ms")
    print(f"Max frame time:     {ft['max']:.2f} ms")
    print(f"Frame-time std dev: {ft['standard_deviation']:.2f} ms")

    # if raw:
    #     print("\n=== Report Metadata ===")
    #     for k, v in raw.items():
    #         print(f"{k}: {v}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("html", help="Metal HUD HTML report")
    parser.add_argument("--json", action="store_true", help="Print JSON")
    parser.add_argument("--csv", metavar="PATH", help="Write one-row CSV")
    args = parser.parse_args()

    try:
        result = parse_report(args.html)
    except Exception as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)

    if args.json:
        print(json.dumps(result, indent=2))
    else:
        print_human(result)

    if args.csv:
        flat = {
            "file": result["file"],
            **result["benchmark"],
            **result["fps"],
            **{f"frame_time_{k}_ms": v for k, v in result["frame_time_ms"].items()},
            **{f"report_{k}": v for k, v in result["raw_report_metrics"].items()},
        }
        with open(args.csv, "w", newline="", encoding="utf-8") as f:
            writer = csv.DictWriter(f, fieldnames=flat.keys())
            writer.writeheader()
            writer.writerow(flat)


if __name__ == "__main__":
    main()
